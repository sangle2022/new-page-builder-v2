#!/usr/bin/env node
// Copies dependency-free shared modules from the function (CommonJS) to the
// React client (ES modules): the lead-form markup (formMarkup.js) and the
// theme variables (theme.js), so the builder matches what the server
// validates and publishes.
//
//   node scripts/sync-shared.js   (run after editing either file)

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const src = path.join(root, 'functions/new_page_builder_v_2_function/src/shared/formMarkup.js');
const dst = path.join(root, 'page-builder/src/builder/formMarkup.js');

const helpers = `
const escapeHtml = (s) =>
  String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
const e = escapeHtml;

function slugify(value, max = 60) {
  return (
    String(value || '')
      .toLowerCase()
      .normalize('NFKD')
      .replace(/[\\u0300-\\u036f]/g, '')
      .replace(/[^a-z0-9\\s-]/g, '')
      .trim()
      .replace(/[\\s_]+/g, '-')
      .replace(/-+/g, '-')
      .replace(/^-|-$/g, '')
      .slice(0, max) || 'page'
  );
}
`;

let code = fs.readFileSync(src, 'utf8');
code = code.replace(/^'use strict';\s*/m, '');
code = code.replace(/^const \{ escapeHtml: e, slugify \} = require\([^)]*\);\s*$/m, helpers);
code = code.replace(/module\.exports = \{([\s\S]*?)\};\s*$/, (m, names) => `export {${names}};\n`);
if (/require\(/.test(code)) throw new Error('formMarkup.js gained a require(); update scripts/sync-shared.js');

const header = '// GENERATED by scripts/sync-shared.js from the function\'s src/shared/formMarkup.js. Do not edit here.\n/* eslint-disable */\n';
fs.writeFileSync(dst, header + code);
console.log(`wrote ${path.relative(root, dst)}`);

// shared/theme.js (no dependencies): theme -> CSS variables, used by the
// editor canvas so it matches published pages exactly.
const themeSrc = path.join(root, 'functions/new_page_builder_v_2_function/src/shared/theme.js');
const themeDst = path.join(root, 'page-builder/src/builder/theme.js');
let theme = fs.readFileSync(themeSrc, 'utf8').replace(/^'use strict';\s*/m, '');
theme = theme.replace(/module\.exports = \{([\s\S]*?)\};\s*$/, (m, names) => `export {${names}};\n`);
if (/require\(/.test(theme)) throw new Error('theme.js gained a require(); update scripts/sync-shared.js');
fs.writeFileSync(themeDst, `// GENERATED by scripts/sync-shared.js from the function's src/shared/theme.js. Do not edit here.\n/* eslint-disable */\n${theme}`);
console.log(`wrote ${path.relative(root, themeDst)}`);
